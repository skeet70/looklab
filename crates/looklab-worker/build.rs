//! Build-time fingerprints of the numerical source closure.
//!
//! `fitter` covers the fit/trust/upload Cargo closure plus worker fit files;
//! `evaluator` covers the model/match closure plus worker assessment files;
//! `model` covers the `looklab-model` closure. Paths are package-relative.

use std::collections::{BTreeMap, BTreeSet, VecDeque};
use std::env;
use std::fs;
use std::io::Read;
use std::path::{Component, Path, PathBuf};

use sha2::{Digest, Sha256};
use toml::Value;

const IGNORED_PARTS: &[&str] = &["target", ".git", "__pycache__"];

#[derive(Clone, Copy)]
struct PackageName(&'static str);

#[derive(Clone, Copy)]
struct WorkerSource(&'static str);

#[derive(Clone, Copy)]
struct DependencyKey(&'static str);

const FITTER_ROOTS: &[PackageName] = &[
    PackageName("looklab-fit"),
    PackageName("looklab-trust"),
    PackageName("looklab-upload"),
];
const EVALUATOR_ROOTS: &[PackageName] =
    &[PackageName("looklab-model"), PackageName("looklab-match")];
const MODEL_ROOTS: &[PackageName] = &[PackageName("looklab-model")];

const FITTER_WORKER_PATHS: &[WorkerSource] = &[
    WorkerSource("crates/looklab-worker/src/model_fit.rs"),
    WorkerSource("crates/looklab-worker/src/model_fit"),
    WorkerSource("crates/looklab-worker/src/pool.rs"),
    WorkerSource("crates/looklab-worker/src/weights.rs"),
    WorkerSource("crates/looklab-worker/src/roots.rs"),
    WorkerSource("crates/looklab-worker/src/body.rs"),
    WorkerSource("crates/looklab-worker/src/meta.rs"),
    WorkerSource("crates/looklab-worker/src/split.rs"),
    WorkerSource("crates/looklab-worker/src/bundle.rs"),
    WorkerSource("crates/looklab-worker/src/db.rs"),
    WorkerSource("crates/looklab-worker/src/source_identity.rs"),
];
const EVALUATOR_WORKER_PATHS: &[WorkerSource] = &[
    WorkerSource("crates/looklab-worker/src/model_assessment.rs"),
    WorkerSource("crates/looklab-worker/src/model_assessment"),
    WorkerSource("crates/looklab-worker/src/assessment"),
];
const FITTER_EXTRA_DEPENDENCIES: &[DependencyKey] = &[DependencyKey("sqlx"), DependencyKey("uuid")];

#[derive(Clone, Copy)]
enum Boundary {
    Fitter,
    Evaluator,
    Model,
}

impl Boundary {
    const fn tag(self) -> &'static str {
        match self {
            Self::Fitter => "fitter",
            Self::Evaluator => "evaluator",
            Self::Model => "model",
        }
    }

    const fn package(self) -> PackageName {
        match self {
            Self::Fitter => PackageName("looklab-fit"),
            Self::Evaluator | Self::Model => PackageName("looklab-model"),
        }
    }
}

#[derive(Clone, Copy)]
enum IncludeMacro {
    Str,
    Bytes,
    Include,
}

fn main() {
    if let Err(error) = run() {
        panic!("source identity: {error}");
    }
}

fn run() -> Result<(), String> {
    let manifest_dir = env::var_os("CARGO_MANIFEST_DIR")
        .map(PathBuf::from)
        .ok_or("CARGO_MANIFEST_DIR is unset")?;
    let root = workspace_root(&manifest_dir)?;
    let root_manifest = read_manifest(&root.join("Cargo.toml"))?;
    let lock = Lockfile::read(&root)?;
    let mut graph = Graph::new(&root, &root_manifest)?;
    let mut rerun = BTreeSet::new();
    rerun.insert(root.join("Cargo.toml"));
    rerun.insert(root.join("Cargo.lock"));

    let common = common_components(&root, &mut rerun)?;
    let fitter = identity(
        Boundary::Fitter,
        &graph.closures(FITTER_ROOTS)?,
        FITTER_EXTRA_DEPENDENCIES,
        FITTER_WORKER_PATHS,
        &common,
        &root,
        &root_manifest,
        &lock,
        &mut rerun,
    )?;
    let evaluator = identity(
        Boundary::Evaluator,
        &graph.closures(EVALUATOR_ROOTS)?,
        &[],
        EVALUATOR_WORKER_PATHS,
        &common,
        &root,
        &root_manifest,
        &lock,
        &mut rerun,
    )?;
    let model = identity(
        Boundary::Model,
        &graph.closures(MODEL_ROOTS)?,
        &[],
        &[],
        &common,
        &root,
        &root_manifest,
        &lock,
        &mut rerun,
    )?;

    let fitter = source_ref(Boundary::Fitter, &fitter)?;
    let evaluator = source_ref(Boundary::Evaluator, &evaluator)?;
    let model = source_ref(Boundary::Model, &model)?;
    let checkpoint = checkpoint_identity(&fitter, &evaluator, &model);

    for path in rerun {
        println!("cargo:rerun-if-changed={}", path.display());
    }
    let out_dir = env::var_os("OUT_DIR")
        .map(PathBuf::from)
        .ok_or("OUT_DIR is unset")?;
    let generated = format!(
        "// Generated by build.rs; do not edit.\n\
         pub const FITTER: &str = \"{fitter}\";\n\
         pub const EVALUATOR: &str = \"{evaluator}\";\n\
         pub const MODEL: &str = \"{model}\";\n\
         pub const CHECKPOINT_IDENTITY: &str = \"{checkpoint}\";\n"
    );
    fs::write(out_dir.join("source_identity.rs"), generated)
        .map_err(|error| format!("write generated source identity: {error}"))
}

fn workspace_root(start: &Path) -> Result<PathBuf, String> {
    let mut directory = start
        .canonicalize()
        .map_err(|error| format!("{}: {error}", start.display()))?;
    loop {
        let manifest = directory.join("Cargo.toml");
        if manifest.is_file() {
            let value = read_manifest(&manifest)?;
            if value.get("workspace").is_some() {
                return Ok(directory);
            }
        }
        directory = directory
            .parent()
            .ok_or_else(|| format!("{} is outside a Cargo workspace", start.display()))?
            .to_path_buf();
    }
}

fn read_manifest(path: &Path) -> Result<Value, String> {
    let text = fs::read_to_string(path).map_err(|error| format!("{}: {error}", path.display()))?;
    toml::from_str(&text).map_err(|error| format!("{}: {error}", path.display()))
}

#[derive(Clone)]
struct Package {
    name: String,
    dir: PathBuf,
    manifest: Value,
}

struct Graph {
    workspace_deps: BTreeMap<String, PathBuf>,
    packages: BTreeMap<String, Package>,
}

impl Graph {
    fn new(root: &Path, manifest: &Value) -> Result<Self, String> {
        let table = manifest
            .get("workspace")
            .and_then(|workspace| workspace.get("dependencies"))
            .and_then(Value::as_table)
            .ok_or("workspace has no [workspace.dependencies]")?;
        let mut workspace_deps = BTreeMap::new();
        for (name, value) in table {
            if let Some(path) = value.get("path").and_then(Value::as_str) {
                workspace_deps.insert(name.clone(), canonical(root, path)?);
            }
        }
        Ok(Self {
            workspace_deps,
            packages: BTreeMap::new(),
        })
    }

    fn closures(&mut self, roots: &[PackageName]) -> Result<Vec<Package>, String> {
        let mut pending: VecDeque<String> = roots.iter().map(|root| root.0.to_string()).collect();
        let mut seen = BTreeSet::new();
        let mut packages = Vec::new();
        while let Some(name) = pending.pop_front() {
            if !seen.insert(name.clone()) {
                continue;
            }
            let package = self.package(&name)?;
            for dependency in self.local_dependencies(&package)? {
                pending.push_back(dependency);
            }
            packages.push(package);
        }
        packages.sort_by_cached_key(|package| package.name.clone());
        Ok(packages)
    }

    fn package(&mut self, name: &str) -> Result<Package, String> {
        if let Some(package) = self.packages.get(name) {
            return Ok(package.clone());
        }
        let directory =
            self.workspace_deps.get(name).cloned().ok_or_else(|| {
                format!("local package {name} is not a workspace path dependency")
            })?;
        let manifest = read_manifest(&directory.join("Cargo.toml"))?;
        let actual = manifest
            .get("package")
            .and_then(|package| package.get("name"))
            .and_then(Value::as_str)
            .ok_or_else(|| format!("{} has no package.name", directory.display()))?;
        if actual != name {
            return Err(format!(
                "{} declares package {actual}, expected {name}",
                directory.display()
            ));
        }
        let package = Package {
            name: name.to_string(),
            dir: directory,
            manifest,
        };
        self.packages.insert(name.to_string(), package.clone());
        Ok(package)
    }

    fn local_dependencies(&mut self, package: &Package) -> Result<Vec<String>, String> {
        let mut names = Vec::new();
        for section in ["dependencies", "build-dependencies"] {
            collect_local(self, package, package.manifest.get(section), &mut names)?;
        }
        if let Some(targets) = package.manifest.get("target").and_then(Value::as_table) {
            for target in targets.values() {
                for section in ["dependencies", "build-dependencies"] {
                    collect_local(self, package, target.get(section), &mut names)?;
                }
            }
        }
        Ok(names)
    }

    fn dependency_name(
        &mut self,
        package: &Package,
        key: &str,
        value: &Value,
    ) -> Result<Option<String>, String> {
        let Some(table) = value.as_table() else {
            return Ok(None);
        };
        let directory = if table.get("workspace").and_then(Value::as_bool) == Some(true) {
            match self.workspace_deps.get(key) {
                Some(directory) => directory.clone(),
                None => return Ok(None),
            }
        } else if let Some(path) = table.get("path").and_then(Value::as_str) {
            canonical(&package.dir, path)?
        } else {
            return Ok(None);
        };
        let manifest = read_manifest(&directory.join("Cargo.toml"))?;
        let name = manifest
            .get("package")
            .and_then(|package| package.get("name"))
            .and_then(Value::as_str)
            .ok_or_else(|| format!("{} has no package.name", directory.display()))?
            .to_string();
        self.workspace_deps.entry(name.clone()).or_insert(directory);
        Ok(Some(name))
    }
}

fn collect_local(
    graph: &mut Graph,
    package: &Package,
    section: Option<&Value>,
    names: &mut Vec<String>,
) -> Result<(), String> {
    let Some(table) = section.and_then(Value::as_table) else {
        return Ok(());
    };
    for (key, value) in table {
        if let Some(dependency) = graph.dependency_name(package, key, value)? {
            names.push(dependency);
        }
    }
    Ok(())
}

fn package_dependency_keys(package: &Package) -> BTreeSet<String> {
    let mut keys = BTreeSet::new();
    for section in ["dependencies", "build-dependencies"] {
        if let Some(table) = package.manifest.get(section).and_then(Value::as_table) {
            keys.extend(table.keys().cloned());
        }
    }
    if let Some(targets) = package.manifest.get("target").and_then(Value::as_table) {
        for target in targets.values() {
            for section in ["dependencies", "build-dependencies"] {
                if let Some(table) = target.get(section).and_then(Value::as_table) {
                    keys.extend(table.keys().cloned());
                }
            }
        }
    }
    keys
}

fn canonical(base: &Path, relative: &str) -> Result<PathBuf, String> {
    let path = base.join(relative);
    path.canonicalize()
        .map_err(|error| format!("{}: {error}", path.display()))
}

fn common_components(
    root: &Path,
    rerun: &mut BTreeSet<PathBuf>,
) -> Result<BTreeMap<String, [u8; 32]>, String> {
    let mut components = BTreeMap::new();
    let toolchain = root.join("rust-toolchain.toml");
    rerun.insert(toolchain.clone());
    if toolchain.is_file() {
        components.insert("toolchain".to_string(), sha256_file(&toolchain)?);
    } else {
        components.insert("toolchain#absent".to_string(), digest_bytes(b"absent"));
    }
    components.insert("cargo-config".to_string(), config_digest(root, rerun)?);
    let build_script =
        PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").ok_or("CARGO_MANIFEST_DIR is unset")?)
            .join("build.rs");
    components.insert("worker/build.rs".to_string(), sha256_file(&build_script)?);
    rerun.insert(build_script);
    Ok(components)
}

fn config_digest(root: &Path, rerun: &mut BTreeSet<PathBuf>) -> Result<[u8; 32], String> {
    let path = root.join(".cargo/config.toml");
    rerun.insert(path.clone());
    if !path.is_file() {
        return Ok(digest_bytes(b"absent"));
    }
    let config = read_manifest(&path)?;
    let mut hasher = Sha256::new();
    hasher.update(b"looklab-cargo-config-v1\0");
    if let Some(build) = config.get("build").and_then(Value::as_table) {
        for key in [
            "rustflags",
            "rustdocflags",
            "rustc-wrapper",
            "rustc-workspace-wrapper",
        ] {
            hash_value(&mut hasher, &format!("build.{key}"), build.get(key));
        }
    }
    if let Some(environment) = config.get("env") {
        hash_value(&mut hasher, "env", Some(environment));
    }
    if let Some(targets) = config.get("target").and_then(Value::as_table) {
        for (target, settings) in targets {
            let Some(settings) = settings.as_table() else {
                continue;
            };
            for key in ["rustflags", "rustdocflags", "linker"] {
                hash_value(
                    &mut hasher,
                    &format!("target.{target}.{key}"),
                    settings.get(key),
                );
            }
        }
    }
    Ok(hasher.finalize().into())
}

fn hash_value(hasher: &mut Sha256, name: &str, value: Option<&Value>) {
    hasher.update(name.as_bytes());
    hasher.update(b"\0");
    match value {
        Some(value) => hasher.update(canonical_value(value).as_bytes()),
        None => hasher.update(b"absent"),
    }
    hasher.update(b"\n");
}

fn canonical_value(value: &Value) -> String {
    match value {
        Value::String(value) => format!("s:{value}"),
        Value::Integer(value) => format!("i:{value}"),
        Value::Float(value) => format!("f:{value}"),
        Value::Boolean(value) => format!("b:{value}"),
        Value::Datetime(value) => format!("d:{value:?}"),
        Value::Array(values) => format!(
            "[{}]",
            values
                .iter()
                .map(canonical_value)
                .collect::<Vec<_>>()
                .join(",")
        ),
        Value::Table(table) => {
            let mut parts: Vec<String> = table
                .iter()
                .map(|(key, value)| format!("{key}={}", canonical_value(value)))
                .collect();
            parts.sort();
            format!("{{{}}}", parts.join(","))
        }
    }
}

struct LockPackage {
    name: String,
    version: String,
    source: Option<String>,
    checksum: Option<String>,
    dependencies: Vec<String>,
}

struct Lockfile {
    format: String,
    packages: Vec<LockPackage>,
    by_name: BTreeMap<String, Vec<usize>>,
    by_key: BTreeMap<(String, String), usize>,
}

impl Lockfile {
    fn read(root: &Path) -> Result<Self, String> {
        let value = read_manifest(&root.join("Cargo.lock"))?;
        let format = value
            .get("version")
            .and_then(Value::as_integer)
            .map_or_else(String::new, |version| version.to_string());
        let records = value
            .get("package")
            .and_then(Value::as_array)
            .ok_or("Cargo.lock has no [[package]] records")?;
        let mut packages = Vec::with_capacity(records.len());
        let mut by_name: BTreeMap<String, Vec<usize>> = BTreeMap::new();
        let mut by_key = BTreeMap::new();
        for record in records {
            let name = record
                .get("name")
                .and_then(Value::as_str)
                .ok_or("Cargo.lock package has no name")?
                .to_string();
            let version = record
                .get("version")
                .and_then(Value::as_str)
                .ok_or("Cargo.lock package has no version")?
                .to_string();
            let source = record
                .get("source")
                .and_then(Value::as_str)
                .map(str::to_string);
            let checksum = record
                .get("checksum")
                .and_then(Value::as_str)
                .map(str::to_string);
            let dependencies: Vec<String> = record
                .get("dependencies")
                .and_then(Value::as_array)
                .map_or_else(Vec::new, |dependencies| {
                    dependencies
                        .iter()
                        .filter_map(Value::as_str)
                        .map(str::to_string)
                        .collect()
                });
            let index = packages.len();
            by_name.entry(name.clone()).or_default().push(index);
            by_key.insert((name.clone(), version.clone()), index);
            packages.push(LockPackage {
                name,
                version,
                source,
                checksum,
                dependencies,
            });
        }
        Ok(Self {
            format,
            packages,
            by_name,
            by_key,
        })
    }

    fn digest(
        &self,
        roots: &BTreeSet<String>,
        local_keys: &BTreeMap<String, BTreeSet<String>>,
    ) -> Result<[u8; 32], String> {
        let mut pending: Vec<usize> = roots
            .iter()
            .flat_map(|name| self.by_name.get(name).into_iter().flatten().copied())
            .collect();
        let mut visited: BTreeSet<(String, String)> = BTreeSet::new();
        while let Some(index) = pending.pop() {
            let package = &self.packages[index];
            let key = (package.name.clone(), package.version.clone());
            if !visited.insert(key) {
                continue;
            }
            let allowed = local_keys.get(&package.name);
            for dependency in &package.dependencies {
                let name = dependency.split_whitespace().next().unwrap_or("");
                if allowed.is_none_or(|allowed| allowed.contains(name)) {
                    pending.extend(self.resolve(dependency));
                }
            }
        }
        let mut hasher = Sha256::new();
        hasher.update(b"looklab-cargo-lock-v1\0");
        hasher.update(self.format.as_bytes());
        hasher.update(b"\0");
        for key in &visited {
            let index = self
                .by_key
                .get(key)
                .copied()
                .ok_or_else(|| format!("Cargo.lock has no package {} {}", key.0, key.1))?;
            let package = &self.packages[index];
            hasher.update(package.name.as_bytes());
            hasher.update(b"\0");
            hasher.update(package.version.as_bytes());
            hasher.update(b"\0");
            hasher.update(package.source.as_deref().unwrap_or("").as_bytes());
            hasher.update(b"\0");
            hasher.update(package.checksum.as_deref().unwrap_or("").as_bytes());
            hasher.update(b"\0");
            let mut dependencies = package.dependencies.clone();
            dependencies.sort();
            for dependency in dependencies {
                hasher.update(dependency.as_bytes());
                hasher.update(b"\n");
            }
            hasher.update(b"\n");
        }
        Ok(hasher.finalize().into())
    }

    fn resolve(&self, dependency: &str) -> Vec<usize> {
        let mut parts = dependency.split_whitespace();
        let Some(name) = parts.next() else {
            return Vec::new();
        };
        let version = parts.next();
        let Some(indices) = self.by_name.get(name) else {
            return Vec::new();
        };
        indices
            .iter()
            .copied()
            .filter(|index| {
                version.is_none_or(|version| self.packages[*index].version.as_str() == version)
            })
            .collect()
    }
}

fn filtered_manifest_digest(
    manifest: &Value,
    dependency_keys: &BTreeSet<String>,
) -> Result<[u8; 32], String> {
    let workspace = manifest
        .get("workspace")
        .ok_or("Cargo.toml has no [workspace]")?;
    let mut hasher = Sha256::new();
    hasher.update(b"looklab-workspace-manifest-v1\0");
    hash_value(&mut hasher, "resolver", workspace.get("resolver"));
    let package = workspace.get("package");
    for key in ["version", "edition", "rust-version"] {
        hash_value(
            &mut hasher,
            key,
            package.and_then(|package| package.get(key)),
        );
    }
    let dependencies = workspace
        .get("dependencies")
        .and_then(Value::as_table)
        .ok_or("workspace has no [workspace.dependencies]")?;
    for key in dependency_keys {
        hasher.update(key.as_bytes());
        hasher.update(b"\0");
        match dependencies.get(key) {
            Some(value) => hasher.update(canonical_value(value).as_bytes()),
            None => hasher.update(b"absent"),
        }
        hasher.update(b"\n");
    }
    Ok(hasher.finalize().into())
}

#[allow(clippy::too_many_arguments)]
fn identity(
    boundary: Boundary,
    packages: &[Package],
    extra_dependencies: &[DependencyKey],
    worker_paths: &[WorkerSource],
    common: &BTreeMap<String, [u8; 32]>,
    root: &Path,
    root_manifest: &Value,
    lock: &Lockfile,
    rerun: &mut BTreeSet<PathBuf>,
) -> Result<String, String> {
    let mut components = BTreeMap::new();
    for (name, digest) in common {
        components.insert(format!("common/{name}"), *digest);
    }
    let local_keys: BTreeMap<String, BTreeSet<String>> = packages
        .iter()
        .map(|package| (package.name.clone(), package_dependency_keys(package)))
        .collect();
    let mut dependency_keys = BTreeSet::new();
    for keys in local_keys.values() {
        dependency_keys.extend(keys.iter().cloned());
    }
    dependency_keys.extend(extra_dependencies.iter().map(|key| key.0.to_string()));
    components.insert(
        "dependency/workspace".to_string(),
        filtered_manifest_digest(root_manifest, &dependency_keys)?,
    );
    let mut lock_roots: BTreeSet<String> = packages
        .iter()
        .map(|package| package.name.clone())
        .collect();
    lock_roots.extend(extra_dependencies.iter().map(|key| key.0.to_string()));
    components.insert(
        "dependency/lock".to_string(),
        lock.digest(&lock_roots, &local_keys)?,
    );

    let mut inputs = BTreeMap::new();
    for package in packages {
        let files = package_files(package)?;
        components.insert(
            format!("crate/{}", package.name),
            package_component(package, &files)?,
        );
        rerun.insert(package.dir.join("src"));
        rerun.insert(package.dir.join("Cargo.toml"));
        rerun.insert(package.dir.join("build.rs"));
        let allowed = [package.dir.clone(), root.join("data")];
        for (relative, path) in referenced_inputs(&files, &allowed, root)? {
            inputs.insert(relative, path);
        }
    }
    for relative in worker_paths {
        let (key, digest) = worker_source_component(root, relative.0, &mut inputs, rerun)?;
        components.insert(key, digest);
    }
    for (relative, path) in inputs {
        components.insert(
            format!("input/{relative}"),
            sha256_file(&path).map_err(|error| format!("{}: {error}", path.display()))?,
        );
        rerun.insert(path);
    }
    let mut hasher = Sha256::new();
    hasher.update(b"looklab-numerical-source-v1\0");
    hasher.update(boundary.tag().as_bytes());
    hasher.update(b"\0");
    for (name, digest) in components {
        hasher.update(name.as_bytes());
        hasher.update(b"\0");
        hasher.update(digest);
        hasher.update(b"\n");
    }
    Ok(hex(&hasher.finalize()))
}

fn package_files(package: &Package) -> Result<Vec<PathBuf>, String> {
    let source = package.dir.join("src");
    if !source.is_dir() {
        return Err(format!("{} has no src directory", package.dir.display()));
    }
    let mut files = Vec::new();
    collect_files(&source, &mut files)?;
    for name in ["Cargo.toml", "build.rs"] {
        let path = package.dir.join(name);
        if path.is_file() {
            files.push(path);
        }
    }
    files.sort();
    files.dedup();
    Ok(files)
}

fn collect_files(directory: &Path, files: &mut Vec<PathBuf>) -> Result<(), String> {
    for entry in
        fs::read_dir(directory).map_err(|error| format!("{}: {error}", directory.display()))?
    {
        let entry = entry.map_err(|error| format!("{}: {error}", directory.display()))?;
        let path = entry.path();
        let kind = entry
            .file_type()
            .map_err(|error| format!("{}: {error}", path.display()))?;
        if kind.is_symlink() {
            return Err(format!(
                "{} is a symlink; source identity hashes regular files",
                path.display()
            ));
        }
        let ignored = entry
            .file_name()
            .to_str()
            .is_some_and(|name| IGNORED_PARTS.contains(&name));
        if ignored {
            continue;
        }
        if kind.is_dir() {
            collect_files(&path, files)?;
        } else if kind.is_file() {
            files.push(path);
        }
    }
    Ok(())
}

fn package_component(package: &Package, files: &[PathBuf]) -> Result<[u8; 32], String> {
    let mut hasher = Sha256::new();
    hasher.update(b"looklab-package-v1\0");
    hasher.update(package.name.as_bytes());
    hasher.update(b"\0");
    for file in files {
        let relative = file
            .strip_prefix(&package.dir)
            .map_err(|error| format!("{}: {error}", file.display()))?;
        hasher.update(portable_path(relative)?.as_bytes());
        hasher.update(b"\0");
        hasher.update(sha256_file(file)?);
        hasher.update(b"\n");
    }
    Ok(hasher.finalize().into())
}

fn worker_source_component(
    root: &Path,
    relative: &str,
    inputs: &mut BTreeMap<String, PathBuf>,
    rerun: &mut BTreeSet<PathBuf>,
) -> Result<(String, [u8; 32]), String> {
    let path = root.join(relative);
    rerun.insert(path.clone());
    if !path.exists() {
        return Ok((format!("worker/{relative}#absent"), digest_bytes(b"absent")));
    }
    let mut files = Vec::new();
    if path.is_dir() {
        collect_files(&path, &mut files)?;
    } else if !path.is_file() {
        return Err(format!("{} is not a file or directory", path.display()));
    } else {
        files.push(path);
    }
    files.sort();
    files.dedup();
    let mut hasher = Sha256::new();
    hasher.update(b"looklab-worker-source-v1\0");
    hasher.update(relative.as_bytes());
    hasher.update(b"\0");
    for file in &files {
        let path = file
            .strip_prefix(root)
            .map_err(|error| format!("{}: {error}", file.display()))?;
        hasher.update(portable_path(path)?.as_bytes());
        hasher.update(b"\0");
        hasher.update(sha256_file(file)?);
        hasher.update(b"\n");
    }
    let allowed = [root.join("crates/looklab-worker"), root.join("data")];
    for (input, path) in referenced_inputs(&files, &allowed, root)? {
        inputs.insert(input, path);
    }
    Ok((format!("worker/{relative}"), hasher.finalize().into()))
}

fn referenced_inputs(
    files: &[PathBuf],
    allowed: &[PathBuf],
    root: &Path,
) -> Result<BTreeMap<String, PathBuf>, String> {
    let mut inputs = BTreeMap::new();
    for file in files.iter().filter(|file| {
        file.extension()
            .and_then(|extension| extension.to_str())
            .is_some_and(|extension| extension == "rs")
    }) {
        let text = fs::read_to_string(file.as_path())
            .map_err(|error| format!("{}: {error}", file.display()))?;
        for line in text.lines() {
            let trimmed = line.trim_start();
            if !trimmed.starts_with("//") && trimmed.contains("#[path") {
                return Err(format!(
                    "{} uses #[path]; source_identity input selection must be extended",
                    file.display()
                ));
            }
        }
        for literal in
            include_literals(&text).map_err(|error| format!("{}: {error}", file.display()))?
        {
            let target = file
                .parent()
                .ok_or_else(|| format!("{} has no parent", file.display()))?
                .join(&literal)
                .canonicalize()
                .map_err(|error| format!("{}: include {literal}: {error}", file.display()))?;
            if !target.is_file() {
                return Err(format!(
                    "{}: include target {literal} is not a file",
                    file.display()
                ));
            }
            if !allowed.iter().any(|allowed| target.starts_with(allowed)) {
                return Err(format!(
                    "{}: include target {literal} is outside the allowed source trees",
                    file.display()
                ));
            }
            let relative = target
                .strip_prefix(root)
                .map_err(|error| format!("{}: {error}", target.display()))?;
            inputs.insert(portable_path(relative)?, target);
        }
    }
    Ok(inputs)
}

fn include_literals(text: &str) -> Result<Vec<String>, String> {
    let bytes = text.as_bytes();
    let mut literals = Vec::new();
    let mut index = 0;
    while index < bytes.len() {
        match bytes[index] {
            b'/' if bytes.get(index + 1) == Some(&b'/') => {
                index = skip_line_comment(bytes, index + 2);
            }
            b'/' if bytes.get(index + 1) == Some(&b'*') => {
                index = skip_block_comment(bytes, index + 2)?;
            }
            b'"' => {
                index = skip_string(bytes, index + 1)?;
            }
            b'\'' => {
                index = skip_quote(bytes, index + 1);
            }
            b'r' if is_raw_string(bytes, index) => {
                index = skip_raw_string(bytes, index)?;
            }
            _ => {
                let boundary = index == 0 || !is_identifier(bytes[index - 1]);
                if let Some((kind, length)) = include_macro(bytes, index).filter(|_| boundary) {
                    let mut cursor = skip_space(bytes, index + length);
                    if bytes.get(cursor) == Some(&b'(') {
                        cursor = skip_space(bytes, cursor + 1);
                    }
                    if bytes.get(cursor) != Some(&b'"') {
                        if matches!(kind, IncludeMacro::Include) {
                            index += length;
                            continue;
                        }
                        return Err(
                            "include macro without a string literal is unsupported".to_string()
                        );
                    }
                    let (literal, next) = parse_string(text, cursor)?;
                    literals.push(literal);
                    index = next;
                    continue;
                }
                index += 1;
            }
        }
    }
    Ok(literals)
}

fn include_macro(bytes: &[u8], index: usize) -> Option<(IncludeMacro, usize)> {
    for (name, kind) in [
        ("include_str!", IncludeMacro::Str),
        ("include_bytes!", IncludeMacro::Bytes),
        ("include!", IncludeMacro::Include),
    ] {
        if bytes[index..].starts_with(name.as_bytes()) {
            return Some((kind, name.len()));
        }
    }
    None
}

fn skip_line_comment(bytes: &[u8], mut index: usize) -> usize {
    while index < bytes.len() {
        if bytes[index] == b'\n' {
            return index + 1;
        }
        index += 1;
    }
    index
}

fn skip_block_comment(bytes: &[u8], mut index: usize) -> Result<usize, String> {
    let mut depth = 1usize;
    while index < bytes.len() {
        if bytes[index..].starts_with(b"/*") {
            depth += 1;
            index += 2;
        } else if bytes[index..].starts_with(b"*/") {
            depth -= 1;
            index += 2;
            if depth == 0 {
                return Ok(index);
            }
        } else {
            index += 1;
        }
    }
    Err("unterminated block comment".to_string())
}

fn skip_string(bytes: &[u8], mut index: usize) -> Result<usize, String> {
    while index < bytes.len() {
        match bytes[index] {
            b'\\' => index += 2,
            b'"' => return Ok(index + 1),
            _ => index += 1,
        }
    }
    Err("unterminated string literal".to_string())
}

fn skip_quote(bytes: &[u8], index: usize) -> usize {
    if bytes.get(index) == Some(&b'\\') {
        let mut cursor = index + 1;
        if bytes.get(cursor) == Some(&b'u') && bytes.get(cursor + 1) == Some(&b'{') {
            cursor += 2;
            while cursor < bytes.len() && bytes[cursor] != b'}' {
                cursor += 1;
            }
            cursor += 1;
        } else {
            cursor += 1;
        }
        return if bytes.get(cursor) == Some(&b'\'') {
            cursor + 1
        } else {
            index + 1
        };
    }
    if bytes.get(index + 1) == Some(&b'\'') {
        return index + 2;
    }
    index + 1
}

fn is_raw_string(bytes: &[u8], index: usize) -> bool {
    if bytes.get(index) != Some(&b'r') {
        return false;
    }
    let mut cursor = index + 1;
    while bytes.get(cursor) == Some(&b'#') {
        cursor += 1;
    }
    bytes.get(cursor) == Some(&b'"')
}

fn skip_raw_string(bytes: &[u8], index: usize) -> Result<usize, String> {
    let mut cursor = index + 1;
    let mut hashes = 0usize;
    while bytes.get(cursor) == Some(&b'#') {
        hashes += 1;
        cursor += 1;
    }
    if bytes.get(cursor) != Some(&b'"') {
        return Ok(index + 1);
    }
    cursor += 1;
    while cursor < bytes.len() {
        if bytes[cursor] == b'"'
            && (1..=hashes).all(|offset| bytes.get(cursor + offset) == Some(&b'#'))
        {
            return Ok(cursor + 1 + hashes);
        }
        cursor += 1;
    }
    Err("unterminated raw string literal".to_string())
}

fn parse_string(text: &str, start: usize) -> Result<(String, usize), String> {
    let mut characters = text[start..].char_indices();
    if characters.next().map(|(_, character)| character) != Some('"') {
        return Err("expected a string literal".to_string());
    }
    let mut value = String::new();
    let mut escaped = false;
    for (offset, character) in characters {
        let index = start + offset;
        if escaped {
            value.push(match character {
                '"' => '"',
                '\\' => '\\',
                'n' => '\n',
                'r' => '\r',
                't' => '\t',
                other => return Err(format!("unsupported string escape \\{other}")),
            });
            escaped = false;
        } else if character == '\\' {
            escaped = true;
        } else if character == '"' {
            return Ok((value, index + 1));
        } else {
            value.push(character);
        }
    }
    Err("unterminated string literal".to_string())
}

fn skip_space(bytes: &[u8], mut index: usize) -> usize {
    while bytes
        .get(index)
        .is_some_and(|byte| byte.is_ascii_whitespace())
    {
        index += 1;
    }
    index
}

fn is_identifier(byte: u8) -> bool {
    byte.is_ascii_alphanumeric() || byte == b'_'
}

fn sha256_file(path: &Path) -> Result<[u8; 32], String> {
    let mut file = fs::File::open(path).map_err(|error| format!("{}: {error}", path.display()))?;
    let mut hasher = Sha256::new();
    let mut buffer = [0u8; 64 * 1024];
    loop {
        let read = file
            .read(&mut buffer)
            .map_err(|error| format!("{}: {error}", path.display()))?;
        if read == 0 {
            break;
        }
        hasher.update(&buffer[..read]);
    }
    Ok(hasher.finalize().into())
}

fn digest_bytes(value: &[u8]) -> [u8; 32] {
    let mut hasher = Sha256::new();
    hasher.update(value);
    hasher.finalize().into()
}

fn portable_path(path: &Path) -> Result<String, String> {
    let mut parts = Vec::new();
    for component in path.components() {
        match component {
            Component::Normal(value) => parts.push(
                value
                    .to_str()
                    .ok_or_else(|| format!("{} is not UTF-8", path.display()))?,
            ),
            Component::CurDir => {}
            _ => return Err(format!("{} is not a relative path", path.display())),
        }
    }
    Ok(parts.join("/"))
}

fn hex(bytes: &[u8]) -> String {
    let mut value = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        value.push_str(&format!("{byte:02x}"));
    }
    value
}

fn source_ref(boundary: Boundary, digest: &str) -> Result<String, String> {
    let value = format!("{}@{digest}", boundary.package().0);
    if value.len() > 256 || value.chars().any(char::is_whitespace) {
        return Err(format!("{value} is not a valid SourceRef"));
    }
    Ok(value)
}

fn checkpoint_identity(fitter: &str, evaluator: &str, model: &str) -> String {
    let mut hasher = Sha256::new();
    hasher.update(b"looklab-numerical-checkpoint-v1\0");
    for value in [fitter, evaluator, model] {
        hasher.update(value.as_bytes());
        hasher.update(b"\0");
    }
    hex(&hasher.finalize())
}
